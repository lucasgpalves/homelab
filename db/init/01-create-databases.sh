#!/bin/bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
	CREATE USER ${GITEA_DB_USER} WITH PASSWORD '${GITEA_DB_PASSWD}';
	CREATE DATABASE ${GITEA_DB_NAME} OWNER ${GITEA_DB_USER};
	GRANT ALL PRIVILEGES ON DATABASE ${GITEA_DB_NAME} TO ${GITEA_DB_USER};

	CREATE USER ${ZABBIX_DB_USER} WITH PASSWORD '${ZABBIX_DB_PASSWD}';
	CREATE DATABASE ${ZABBIX_DB_NAME} OWNER ${ZABBIX_DB_USER};
	GRANT ALL PRIVILEGES ON DATABASE ${ZABBIX_DB_NAME} TO ${ZABBIX_DB_USER};
EOSQL
